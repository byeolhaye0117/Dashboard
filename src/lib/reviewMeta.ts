/** 지점 이름을 주면 그 지점에 어울리는 키워드 후보를 돌려준다 */
export function keywordsFor(branchName: string): string[] {
  const name = (branchName ?? "").replace(/\s/g, "");
  const set = KEYWORD_SETS.find((k) => name.includes(k.match));
  return [...(set?.words ?? []), ...COMMON_KEYWORDS];
}

