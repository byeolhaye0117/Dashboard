/**
 * 매출 유형 기본값 (화면·서버 양쪽에서 쓴다)
 *
 * ── 왜 따로 파일인가 ─────────────────────────────────────────
 * 세 화면(상품 담기 · 이용권 고치기 · 결제 고치기)이 각자 목록을 적어
 * 두었더니, 한 곳에만 값이 늘어 화면마다 고를 수 있는 것이 달랐다.
 * 서버(회원 화면 page)도 같은 목록을 봐야 해서 여기 한 줄로 둔다.
 * 이 파일은 구글 접속 코드를 안 물고 있어 화면 쪽에서도 그대로 쓸 수 있다.
 *
 * ── 「PT」에 대하여 ──────────────────────────────────────────
 * 대표님이 넣으라 하신 값이다. 신규·재등록을 가르는 말이 아니라서 매출
 * 화면은 이 값을 신규/재등록 판단에 쓰지 않는다 — 대신 그 회원이 전에
 * 같은 갈래를 끊었는지 보고 알아서 가른다. 그러니 PT 로 두어도 재등록률
 * 에서 빠지지 않는다.
 */
export const SALE_TYPES = ["신규", "재등록", "PT", "기타매출"];

/**
 * 시트에 적힌 매출유형을 네 가지 가운데 하나로
 *
 * 「재등록」 「재 등록」 「재등록(PT)」이 다 같은 말이 되게 앞글자로 본다.
 * 아무것도 안 적힌 옛 줄은 「미분류」다 — 「기타매출」과 다르다. 기타매출은
 * 사물함처럼 등록이 아닌 것을 일부러 고르신 것이고, 미분류는 고른 적이
 * 없는 것이라 화면이 짐작해도 되는 자리다.
 *
 * 「PT」도 따로 돌려준다. 이것은 등록이 아니라는 말이 아니라 신규인지
 * 재등록인지를 안 고르신 것이라, 기타매출과 한 칸에 넣으면 PT 를 고르신
 * 순간 그 회원이 등록에서 통째로 빠진다.
 *
 * 매출 화면과 회원 화면이 같은 말을 해야 해서 여기 한 줄로 둔다.
 */
export function typeOf(
  v: string
): "신규" | "재등록" | "PT" | "기타매출" | "미분류" {
  const t = (v ?? "").trim();
  if (t.startsWith("재등")) return "재등록";
  if (t.startsWith("신규")) return "신규";
  if (t.replace(/\s/g, "").toUpperCase() === "PT") return "PT";
  if (t) return "기타매출";
  return "미분류";
}

/**
 * 이 결제는 등록인가, 등록이면 신규인가 재등록인가
 *
 * 고르신 값이 먼저다. 「기타매출」이면 등록이 아니다(빈 값). PT 이거나
 * 아무것도 안 고르신 옛 줄이면, 그 회원이 전에 끊은 적이 있는지 보고 가른다.
 */
export function joinKindOf(
  매출유형: string,
  전에끊은적있나: boolean
): "신규" | "재등록" | "" {
  const t = typeOf(매출유형);
  if (t === "신규" || t === "재등록") return t;
  if (t === "기타매출") return "";
  return 전에끊은적있나 ? "재등록" : "신규";
}
