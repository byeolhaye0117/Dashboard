/**
 * 창 밖을 눌러 닫기 — 다만 「눌러서」만
 *
 * ── 무엇이 잘못돼 있었나 ─────────────────────────────────────
 * 창 바깥(어두운 바탕)에 onClick 으로 닫기를 걸어 두었다. 그런데 브라우저는
 * 누른 자리와 뗀 자리가 다르면 그 둘을 함께 감싸는 바깥쪽에 click 을 준다.
 *
 * 그래서 금액 칸 안에서 마우스를 눌러 글자를 죽 긁다가 창 밖에서 손을 떼면,
 * click 이 어두운 바탕에서 난 것으로 잡혀 창이 그냥 닫혔다. 고치던 금액이
 * 통째로 날아간다. 금액을 한 번에 잡으려다 창이 튕겨 나가는 것이 이것이다.
 *
 * 누르기 시작한 자리가 바탕이었을 때만 닫는다. 창 안에서 시작한 드래그는
 * 어디서 떼든 닫히지 않는다.
 *
 * 시작 자리를 파일 하나에 기억해 둔다 — 누르고 떼는 일은 한 번에 하나뿐이라
 * 창이 여럿 겹쳐 있어도 서로 섞이지 않는다.
 */
type 눌림 = { target: unknown; currentTarget: unknown };

let 바탕에서시작 = false;

export function backdrop(close: () => void) {
  return {
    onMouseDown: (e: 눌림) => {
      바탕에서시작 = e.target === e.currentTarget;
    },
    onClick: (e: 눌림) => {
      const 바탕에서끝 = e.target === e.currentTarget;
      const 닫자 = 바탕에서시작 && 바탕에서끝;
      바탕에서시작 = false;
      if (닫자) close();
    },
  };
}
